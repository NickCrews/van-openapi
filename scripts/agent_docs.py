def render_routing(spec, base):
    """The task -> operation table, from each operation's x-task."""
    lines = ["| Task | Operation |", "| --- | --- |"]
    for _path, _method, op in operations(spec):
        task = op.get("x-task")
        if not task:
            raise SystemExit(f"{op['operationId']} has no x-task — add one to the spec")
        op_id = op["operationId"]
        lines.append(f"| {cell(task)} | [`{op_id}`]({base}operations/{op_id}.md) |")
    return lines


def render_traps(spec, base):
    """The cross-cutting gotcha list, from the spec's root-level x-traps."""
    op_ids = {op["operationId"] for _p, _m, op in operations(spec)}
    behavior_ids = set(load_transcripts()[0])

    lines = []
    for trap in spec.get("x-traps", []):
        links = []
        for ref in trap.get("see", []):
            if ref in op_ids:
                links.append(f"[`{ref}`]({base}operations/{ref}.md)")
            elif ref in behavior_ids:
                links.append(f"[`{ref}`]({base}behaviors/{ref}.md)")
            else:
                raise SystemExit(
                    f"x-traps entry points at '{ref}', which is neither an "
                    f"operationId nor a transcript id"
                )
        suffix = f" ({', '.join(links)})" if links else ""
        lines.append(f"- {trap['text']}{suffix}")
    return lines


BLOCKS = {"routing": render_routing, "traps": render_traps}


def sync_blocks(spec, check):
    """Refresh the generated blocks inside the hand-written prose.

    Returns the paths whose blocks were out of date.
    """
    stale = []
    for path in sorted(SKILL.rglob("*.md")):
        if OUT in path.parents and path.parent.name != "recipes":
            continue  # fully generated already
        original = path.read_text()
        if "<!-- BEGIN GENERATED:" not in original:
            continue
        # How to get from this file's directory back into reference/.
        base = os.path.relpath(OUT, path.parent) + "/"
        base = "" if base == "./" else base

        def replace(m):
            name = m.group("name")
            if name not in BLOCKS:
                raise SystemExit(f"{path.name}: unknown generated block '{name}'")
            body = "\n".join(BLOCKS[name](spec, base))
            return f"{m.group(1)}\n{body}\n\n{m.group(4)}"

        updated = BLOCK.sub(replace, original)
        if updated == original:
            continue
        if check:
            stale.append(str(path.relative_to(SKILL)))
        else:
            path.write_text(updated)
    return stale


def check_spec_symlink():
    """The skill ships the spec itself, as a symlink so it can never be a stale copy."""
    link = SKILL / "openapi.json"
    want = os.path.relpath(REPO / "openapi.json", SKILL)
    if not link.is_symlink():
        return f"{link.relative_to(SKILL)} must be a symlink to {want}"
    if os.readlink(link) != want:
        return f"{link.relative_to(SKILL)} points at {os.readlink(link)}, expected {want}"
    if not link.resolve().exists():
        return f"{link.relative_to(SKILL)} is a broken symlink"
    return None


def check_references():
    """Every relative link in the skill must resolve.

    This is what stops the hand-written prose rotting silently: rename an
    operation or delete a transcript and the recipes that pointed at it fail CI.
    """
    broken = []
    for path in sorted(SKILL.rglob("*.md")):
        for m in re.finditer(r"\]\(([^)]+)\)", path.read_text()):
            target = m.group(1).split("#")[0]
            if not target or target.startswith(("http://", "https://", "mailto:")):
                continue
            if not (path.parent / target).resolve().exists():
                broken.append(f"{path.relative_to(SKILL)} -> {target}")
    return broken


def build(spec):
    schemas = Schemas(spec)
    by_id, by_pointer = load_transcripts()
    files = {}

    for path, method, op in operations(spec):
        related = by_pointer.get(pointer_for(path, method), [])
        related = sorted(related, key=lambda t: t["id"])
        files[f"operations/{op['operationId']}.md"] = render_operation(
            spec, schemas, path, method, op, related
        )

    for name in sorted(schemas.own_page):
        schema = schemas.all[name]
        used_by = [
            op["operationId"]
            for _, _, op in operations(spec)
            if f'"#/components/schemas/{name}"' in json.dumps(op)
        ]
        body = [BANNER, "", f"# {name}", ""]
        if used_by:
            refs = ", ".join(f"[`{o}`](../operations/{o}.md)" for o in used_by)
            body += [f"Used directly by: {refs}", ""]
        body += schemas.table(schema)
        files[f"schemas/{name}.md"] = body

    for t in by_id.values():
        files[f"behaviors/{t['id']}.md"] = render_transcript(t)

    files["INDEX.md"] = render_index(spec, by_pointer)
    files["COVERAGE.md"] = render_coverage()
    files["ERRORS.md"] = render_errors(spec, schemas)
    return files


def main():
    check = "--check" in sys.argv
    spec = json.loads((REPO / "openapi.json").read_text())
    files = build(spec)

    stale = []
    for rel, lines in files.items():
        target = OUT / rel
        body = re.sub(r"\n{3,}", "\n\n", "\n".join(lines).rstrip() + "\n")
        if check:
            if not target.exists() or target.read_text() != body:
                stale.append(rel)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(body)

    # Files left behind by a renamed operation or a deleted transcript would
    # otherwise keep being served as current.
    expected = {OUT / rel for rel in files}
    for existing in OUT.rglob("*.md"):
        if existing.parent.name == "recipes" or existing in expected:
            continue
        if check:
            stale.append(f"{existing.relative_to(OUT)} (orphaned)")
        else:
            existing.unlink()

    stale += [f"{rel} (generated block)" for rel in sync_blocks(spec, check)]

    # Run last: the link check is only meaningful once everything is written.
    broken = check_references()
    symlink_problem = check_spec_symlink()
    if symlink_problem:
        broken.append(symlink_problem)

    if check:
        if stale:
            print("agent docs are stale — run `make agent-docs` and commit:", file=sys.stderr)
            for rel in sorted(stale):
                print(f"  {rel}", file=sys.stderr)
        if broken:
            print("dangling references in the skill:", file=sys.stderr)
            for ref in broken:
                print(f"  {ref}", file=sys.stderr)
        if stale or broken:
            sys.exit(1)
        print("agent docs are up to date")
    else:
        if broken:
            print("dangling references in the skill:", file=sys.stderr)
            for ref in broken:
                print(f"  {ref}", file=sys.stderr)
            sys.exit(1)
        print(f"wrote {len(files)} files to {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
