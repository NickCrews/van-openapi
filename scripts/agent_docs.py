class Schemas:
    """Resolves $refs, deciding at each one whether to link out or inline."""

    def __init__(self, spec):
        self.all = spec["components"]["schemas"]
        self.own_page = {
            name
            for name, schema in self.all.items()
            if len(json.dumps(schema)) >= OWN_PAGE_CHARS
        }

    def deref(self, schema):
        """Follow $ref and flatten allOf into a single object schema."""
        seen = set()
        while isinstance(schema, dict) and "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[-1]
            if name in seen:
                return {}
            seen.add(name)
            schema = self.all.get(name, {})
        if isinstance(schema, dict) and "allOf" in schema:
            merged = {"type": "object", "properties": {}, "required": []}
            for part in schema["allOf"]:
                part = self.deref(part)
                merged["properties"].update(part.get("properties", {}))
                merged["required"] += part.get("required", [])
                for key in ("description", "type"):
                    if key in part and key not in merged:
                        merged[key] = part[key]
            for key, value in schema.items():
                if key != "allOf":
                    merged.setdefault(key, value)
            return merged
        return schema if isinstance(schema, dict) else {}

    def ref_name(self, schema):
        """The schema name if this is a bare $ref, else None."""
        if isinstance(schema, dict) and "$ref" in schema:
            return schema["$ref"].rsplit("/", 1)[-1]
        return None

    def type_of(self, schema, depth, base="../"):
        """Render the Type column, linking out to any schema with its own page.

        `base` is the path back to reference/ from the page being written, so
        the same renderer serves pages at the root and in subdirectories.
        """
        name = self.ref_name(schema)
        if name and name in self.own_page:
            return f"[{name}]({base}schemas/{name}.md)"
        if name in ERROR_SCHEMAS:
            return f"[{name}]({base}ERRORS.md#{name.lower()})"
        resolved = self.deref(schema)
        for key in ("oneOf", "anyOf"):
            if resolved.get(key):
                joiner = " or " if key == "oneOf" else " and/or "
                return joiner.join(self.type_of(alt, depth, base) for alt in resolved[key])
        kind = resolved.get("type")
        if isinstance(kind, list):
            nullable = "null" in kind
            kind = next((k for k in kind if k != "null"), "any")
            suffix = " or null" if nullable else ""
        else:
            suffix = ""
        if kind == "array":
            return f"array of {self.type_of(resolved.get('items', {}), depth, base)}{suffix}"
        if kind == "object" and resolved.get("properties"):
            return f"object{suffix}"
        fmt = resolved.get("format")
        return f"{kind or 'any'}{f' ({fmt})' if fmt else ''}{suffix}"

    def rows(self, schema, base="../", prefix="", depth=0, seen=None):
        """One row per property, nested objects flattened to dotted paths."""
        seen = set(seen or ())
        name = self.ref_name(schema)
        if name:
            if name in seen:
                return []
            seen.add(name)
        resolved = self.deref(schema)
        if resolved.get("type") == "array":
            return self.rows(resolved.get("items", {}), base, prefix, depth, seen)

        required = set(resolved.get("required", []))
        out = []
        for prop, sub in (resolved.get("properties") or {}).items():
            path = f"{prop}" if not prefix else f"{prefix}.{prop}"
            sub_name = self.ref_name(sub)
            resolved_sub = self.deref(sub)

            notes = [resolved_sub.get("description") or sub.get("description") or ""]
            enum = enum_of(self, sub)
            if enum:
                notes.append("One of: " + ", ".join(f"`{v}`" for v in enum) + ".")
            examples = resolved_sub.get("examples") or (
                [resolved_sub["example"]] if "example" in resolved_sub else []
            )
            if examples:
                notes.append("e.g. " + ", ".join(f"`{e}`" for e in examples[:2]))

            out.append(
                f"| `{path}`{' *' if prop in required else ''} "
                f"| {self.type_of(sub, depth, base)} | {cell(' '.join(n for n in notes if n))} |"
            )

            # Recurse into inline objects and arrays of them, but stop at
            # anything that has its own page — that is what the link is for.
            if sub_name and sub_name in self.own_page:
                continue
            if depth >= 3:
                continue
            target = resolved_sub
            if target.get("type") == "array":
                item_name = self.ref_name(target.get("items", {}))
                if item_name and item_name in self.own_page:
                    continue
                target = self.deref(target.get("items", {}))
            if target.get("properties"):
                out += self.rows(target, base, path, depth + 1, seen)
        return out

    def table(self, schema, base="../", title=None):
        rows = self.rows(schema, base)
        if not rows:
            resolved = self.deref(schema)
            desc = resolved.get("description")
            return [f"_{cell(desc)}_"] if desc else ["_No documented properties._"]
        lines = []
        if title:
            lines.append(title)
        resolved = self.deref(schema)
        if resolved.get("description"):
            lines += [resolved["description"], ""]
        lines += ["| Property | Type | Notes |", "| --- | --- | --- |", *rows]
        lines += ["", "`*` = required."]
        return lines


