def example_call(spec, path, method, op):
    """Synthesise the shortest curl that exercises the operation.

    The x-codeSamples in the spec are multi-step scripts of 1.5k-8k characters
    — too heavy for the top of a reference page. They stay reachable through
    the behavior pages; this is just the shape of one call.
    """
    url = path
    query = []
    for param in op.get("parameters", []):
        value = param.get("example")
        if value is None:
            continue
        if param["in"] == "path":
            url = url.replace("{" + param["name"] + "}", str(value))
        elif param["in"] == "query" and param.get("required"):
            query.append(f"{param['name']}={value}")

    # No required query parameters is not the same as none worth showing: an
    # endpoint that refuses an empty query needs one in the example.
    if not query and method == "get":
        for param in op.get("parameters", []):
            if param["in"] == "query" and param.get("example") is not None:
                query.append(f"{param['name']}={param['example']}")
                break

    full = url + ("?" + "&".join(query) if query else "")
    lines = ["```bash", f"curl -sS -X {method.upper()} \\"]
    lines.append(f"  'https://api.securevan.com/v4{full}' \\")
    lines.append('  -u "app-name:$NGP_API_KEY|1" \\')

    body = None
    content = (op.get("requestBody") or {}).get("content", {}).get("application/json", {})
    examples = content.get("examples") or {}
    if examples:
        chosen = examples.get("minimal") or next(iter(examples.values()))
        body = chosen.get("value")
    if body is not None:
        lines.append("  -H 'Content-Type: application/json' \\")
        payload = json.dumps(body, indent=2)
        lines.append(f"  -d '{payload}'")
    else:
        lines[-1] = lines[-1].rstrip(" \\")
    lines.append("```")
    return lines


def render_operation(spec, schemas, path, method, op, transcripts):
    op_id = op["operationId"]
    lines = [
        BANNER,
        "",
        f"# {op_id} — {method.upper()} {path}",
        "",
        op["summary"],
        "",
    ]

    # Front-loaded, because an agent that stops reading after the first screen
    # should still have been warned. Every claim here is a recorded exchange.
    if transcripts:
        lines += ["## Verified behaviors", ""]
        for t in transcripts:
            lines.append(f"- **{t['title']}** — {t['claim']} ([replay](../behaviors/{t['id']}.md))")
        lines.append("")

    lines += ["## Behavior", "", op["description"], ""]

    discrepancies = collect_discrepancies(op)
    if discrepancies:
        lines += ["## Differs from the official docs", ""]
        lines += [f"- **{where}** — {note}" for where, note in discrepancies]
        lines.append("")

    lines += ["## Example", "", *example_call(spec, path, method, op), ""]

    params = op.get("parameters", [])
    for kind, heading in (("path", "Path parameters"), ("query", "Query parameters")):
        subset = [p for p in params if p["in"] == kind]
        if not subset:
            continue
        lines += [f"## {heading}", "", "| Name | Type | Notes |", "| --- | --- | --- |"]
        for p in subset:
            notes = [p.get("description", "")]
            enum = enum_of(schemas, p.get("schema", {}))
            if enum:
                notes.append("One of: " + ", ".join(f"`{v}`" for v in enum) + ".")
            star = " *" if p.get("required") else ""
            lines.append(
                f"| `{p['name']}`{star} | {schemas.type_of(p.get('schema', {}), 0)} "
                f"| {cell(' '.join(n for n in notes if n))} |"
            )
        lines += ["", "`*` = required.", ""]

    body = op.get("requestBody")
    if body:
        media = body.get("content", {}).get("application/json", {})
        schema = media.get("schema", {})
        required = " (required)" if body.get("required") else " (optional)"
        name = schemas.ref_name(schema)
        lines += [f"## Request body{required}", ""]
        if name and name in schemas.own_page:
            lines += [f"See [{name}](../schemas/{name}.md).", ""]
        else:
            lines += [*schemas.table(schema), ""]

    lines += ["## Responses", "", "| Status | Meaning | Body |", "| --- | --- | --- |"]
    shared = {}
    for code, resp in op["responses"].items():
        shared_name = resp["$ref"].rsplit("/", 1)[-1] if "$ref" in resp else None
        resolved = spec["components"]["responses"][shared_name] if shared_name else resp
        schema = (resolved.get("content", {}).get("application/json", {}) or {}).get("schema", {})
        name = schemas.ref_name(schema)
        if name and name in schemas.own_page:
            shape = f"[{name}](../schemas/{name}.md)"
        elif name in ERROR_SCHEMAS:
            shape = f"[{name}](../ERRORS.md#{name.lower()})"
        elif name:
            shape = f"`{name}`"
        elif schema:
            shape = schemas.type_of(schema, 0)
        else:
            shape = "_empty_"

        meaning = cell(resolved.get("description"))
        if shared_name:
            # The shared descriptions run to 700 characters and say the same
            # thing on every page. First sentence here, the rest in ERRORS.md.
            head = re.split(r"(?<=[.!?])\s", meaning, maxsplit=1)[0]
            meaning = f"{head} ([details](../ERRORS.md#{shared_name.lower()}))"
            shared[shared_name] = resolved
        lines.append(f"| `{code}` | {meaning} | {shape} |")
    lines.append("")

    # Inline the small operation-specific response schemas the table only
    # named, so the common case needs no second file read.
    shown = set()
    for code, resp in op["responses"].items():
        if "$ref" in resp:
            continue
        schema = (resp.get("content", {}).get("application/json", {}) or {}).get("schema", {})
        name = schemas.ref_name(schema)
        if not name or name in schemas.own_page or name in ERROR_SCHEMAS or name in shown:
            continue
        shown.add(name)
        lines += [f"### `{code}` body — {name}", "", *schemas.table(schema), ""]

    links = {}
    for resp in op["responses"].values():
        links.update(resp.get("links") or {})
    if links:
        lines += ["## What to call next", ""]
        for label, link in links.items():
            target = link.get("operationId", label)
            lines.append(f"- [`{target}`]({target}.md) — {cell(link.get('description'))}")
        lines.append("")

    return lines


def collect_discrepancies(node, crumbs=()):
    """Every x-docs-discrepancy at or under an operation, with a readable label."""
    out = []
    if isinstance(node, dict):
        if "x-docs-discrepancy" in node:
            label = " / ".join(str(c) for c in crumbs) or "the operation"
            out.append((label, node["x-docs-discrepancy"]))
        for key, value in node.items():
            if key == "x-docs-discrepancy":
                continue
            out += collect_discrepancies(value, crumbs + (key,))
    elif isinstance(node, list):
        for i, value in enumerate(node):
            crumb = value.get("name", str(i)) if isinstance(value, dict) else str(i)
            out += collect_discrepancies(value, crumbs + (crumb,))
    return out


