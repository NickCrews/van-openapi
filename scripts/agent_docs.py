def render_index(spec, by_pointer):
    lines = [
        BANNER,
        "",
        "# Operation index",
        "",
        "Every operation the spec covers. `Search terms` is the vocabulary a",
        "request is likely to use — grep this file for the user's own words",
        "before guessing at an operationId.",
        "",
        "Pages are at `operations/<operationId>.md`.",
        "",
        "| Operation | Endpoint | What it does | Search terms |",
        "| --- | --- | --- | --- |",
    ]
    for path, method, op in operations(spec):
        op_id = op["operationId"]
        keywords = ", ".join(op.get("x-keywords", []))
        lines.append(
            f"| [`{op_id}`](operations/{op_id}.md) | `{method.upper()} {path}` "
            f"| {cell(op['summary'])} | {cell(keywords)} |"
        )

    lines += [
        "",
        "## Verified behaviors",
        "",
        "Recorded request/response exchanges, at `behaviors/<id>.md`. Each one is",
        "already summarised at the top of the operation page it applies to, so",
        "read these only when you want the actual traffic.",
        "",
        "| Behavior | Title |",
        "| --- | --- |",
    ]
    everything = {t["id"]: t for ts in by_pointer.values() for t in ts}
    for t in sorted(everything.values(), key=lambda t: t["id"]):
        lines.append(f"| [`{t['id']}`](behaviors/{t['id']}.md) | {cell(t['title'])} |")
    return lines


def render_errors(spec, schemas):
    """The error contract, once, instead of on all fifteen operation pages."""
    lines = [
        BANNER,
        "",
        "# Errors",
        "",
        "Every operation can return `401`, `429` and `500`; most can also return",
        "`400`. The operation pages name the status and link here for the detail.",
        "",
    ]
    for name, resp in spec["components"]["responses"].items():
        lines += [f"## {name}", "", resp.get("description", ""), ""]
        schema = (resp.get("content", {}).get("application/json", {}) or {}).get("schema", {})
        shape = schemas.type_of(schema, 0, base="") if schema else "_empty body_"
        lines += [f"Body: {shape}", ""]

    lines += ["## Error body shapes", ""]
    for name in ("ErrorResponse", "AspNetError", "Error"):
        if name not in schemas.all:
            continue
        lines += [f"### {name}", "", *schemas.table(schemas.all[name], base=""), ""]
    return lines


def status_rows():
    """Parse the endpoint survey table out of STATUS.md.

    Only the five-column survey table is wanted; STATUS.md also carries a
    two-column table of sandbox fixtures further down.
    """
    for line in (REPO / "STATUS.md").read_text().splitlines():
        line = line.strip()
        if not line.startswith("|") or not line.endswith("|"):
            continue
        cells = [c.strip() for c in line[1:-1].split("|")]
        if len(cells) != 5:
            continue
        if cells[0] == "Endpoint group" or set(cells[0]) <= set("-: "):
            continue
        yield cells


def render_coverage():
    """Turn the STATUS.md survey into a boundary map.

    This is the file that lets an agent answer "you cannot do that with this
    spec" in one read instead of discovering it over a dozen failed requests.
    """
    covered, researched, unknown = [], [], []
    for group, paths, _sources, status, _last in status_rows():
        row = (group, paths, status)
        plain = status.lower()
        if "validated" in plain or "spec'd" in plain:
            covered.append(row)
        elif "unresearched" in plain:
            unknown.append(row)
        else:
            researched.append(row)

    lines = [
        BANNER,
        "",
        "# Coverage — what this spec does and does not cover",
        "",
        "The NGP VAN API is much larger than this spec. Before concluding that",
        "something is impossible, check which of the three sections below it",
        "falls into. **Never invent an endpoint that is not listed here.**",
        "",
        "## 1. In the spec, verified against the live API",
        "",
        "These have pages under `operations/`. Behavior in them has been probed.",
        "",
        "| Endpoint group | Paths | Status |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {cell(g)} | {cell(p)} | {cell(s)} |" for g, p, s in covered]

    lines += [
        "",
        "## 2. Real endpoints, researched but deliberately not in the spec",
        "",
        "These exist. The spec omits them for the reason given — usually that the",
        "sandbox key cannot reach them, so the success shape was never observed.",
        "You can still call them; you just have no schema for the response.",
        "",
        "| Endpoint group | Paths | Why not spec'd |",
        "| --- | --- | --- |",
    ]
    lines += [f"| {cell(g)} | {cell(p)} | {cell(s)} |" for g, p, s in researched]

    lines += [
        "",
        "## 3. Known to exist, not yet researched",
        "",
        "Paths gathered from the official docs and the NGPVAN/van-cli source but",
        "never probed. **If a request needs one of these, say so rather than",
        "improvising with the endpoints in section 1.** Bulk questions — totals",
        "across a whole database, exports, anything that would otherwise need",
        "thousands of paged requests — almost always land here, under Export Jobs,",
        "Saved Lists or Changed Entity Export Jobs.",
        "",
        "| Endpoint group | Paths |",
        "| --- | --- |",
    ]
    lines += [f"| {cell(g)} | {cell(p)} |" for g, p, _ in unknown]

    lines += [
        "",
        "## Confirmed absent",
        "",
        "- `GET /people/quickSearch` — 404 \"No HTTP resource\". It does not exist,",
        "  in any casing. Use `GET /people` (searchPeople).",
        "- There is no count-by-attribute or aggregate endpoint of any kind. The",
        "  only total the API volunteers is `count` in the pagination envelope,",
        "  which counts matches for a query you already had to specify.",
        "",
        "## Where the evidence lives",
        "",
        "- Research status and sandbox notes: [STATUS.md](../../../../STATUS.md)",
        "- Departures from the official docs: [DISCREPANCIES.md](../../../../DISCREPANCIES.md)",
        "- Per-field evidence: the `x-provenance` fields in",
        "  [openapi.json](../../../../openapi.json), omitted from these pages.",
    ]
    return lines


