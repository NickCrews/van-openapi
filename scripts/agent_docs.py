#!/usr/bin/env python3
"""Generate the agent-browsable reference under .claude/skills/van-api/reference/.

The spec is ~114k tokens — far too much for an agent to load to answer one
question. This slices it into files small enough to read on demand and named
predictably enough to reach without consulting an index:

    reference/INDEX.md                  every operation on one line, with the
                                        user vocabulary from x-keywords
    reference/COVERAGE.md               what is *not* in the spec, from STATUS.md
    reference/operations/<operationId>.md
    reference/schemas/<SchemaName>.md
    reference/behaviors/<transcript id>.md

SKILL.md and reference/recipes/ are hand-written and never touched here.

Two conventions the whole thing rests on:

  * Filenames are operationIds and transcript ids, so an agent that has seen
    either in the spec can construct the path without a lookup.
  * Every property is one table row, newlines collapsed, so a single
    `grep -rn phoneNumber reference/` returns the full description as one hit.
"""

import json
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKILL = REPO / ".claude" / "skills" / "van-api"
OUT = SKILL / "reference"

# Hand-written prose can still carry spec-derived tables, kept in sync through
# markers rather than by hand:
#     <!-- BEGIN GENERATED: routing -->  ...  <!-- END GENERATED: routing -->
BLOCK = re.compile(
    r"(<!-- BEGIN GENERATED: (?P<name>[\w-]+) -->\n)(?P<body>.*?)(<!-- END GENERATED: (?P=name) -->)",
    re.DOTALL,
)

HTTP_METHODS = ("get", "put", "post", "delete", "patch", "options", "head")

# A schema earns its own page once inlining it at every use site costs more
# than the extra file read. 1600 chars ~ 400 tokens is where that crosses over
# for this spec; everything smaller is duplicated wherever it is used.
OWN_PAGE_CHARS = 1600

# The error contract is identical on almost every operation — 401/429/500 on all
# fifteen, 400 on thirteen. Repeating it per page costs ~8k tokens of pure
# duplication, so it lives once in ERRORS.md and the tables link to it.
ERROR_SCHEMAS = {"ErrorResponse", "AspNetError", "Error"}

BANNER = "<!-- Generated by `make agent-docs` from openapi.json, transcripts/ and STATUS.md. Do not edit by hand. -->"


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------


def cell(text):
    """Collapse a description into one table cell: no newlines, no bare pipes."""
    if not text:
        return ""
    return re.sub(r"\s+", " ", str(text)).replace("|", "\\|").strip()


def operations(spec):
    """Yield (path, method, operation) for every operation in the spec."""
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method in HTTP_METHODS:
                yield path, method, op


def enum_of(schemas, schema):
    """Allowed values, looking through arrays — an array's enum sits on `items`."""
    resolved = schemas.deref(schema)
    if resolved.get("type") == "array":
        resolved = schemas.deref(resolved.get("items", {}))
    return resolved.get("enum")


def write(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    body = "\n".join(lines).rstrip() + "\n"
    body = re.sub(r"\n{3,}", "\n\n", body)
    path.write_text(body)


