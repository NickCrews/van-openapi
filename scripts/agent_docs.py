def load_transcripts():
    """Transcript id -> record, plus operation-pointer -> [transcript]."""
    by_id, by_pointer = {}, {}
    for path in sorted((REPO / "transcripts").glob("*.json")):
        t = json.loads(path.read_text())
        by_id[t["id"]] = t
        for pointer in t.get("spec", []):
            by_pointer.setdefault(pointer, []).append(t)
    return by_id, by_pointer


def pointer_for(path, method):
    return f"#/paths/~1{path.lstrip('/').replace('/', '~1')}/{method}"


def render_transcript(t):
    """A behavior page: the claim, then the exchanges as runnable curl."""
    lines = [
        BANNER,
        "",
        f"# {t['title']}",
        "",
        f"**Claim.** {t['claim']}",
        "",
    ]
    ops = t.get("spec", [])
    if ops:
        pretty = ", ".join(f"`{p.split('/paths/')[-1]}`" for p in ops)
        lines += [f"Applies to: {pretty}", ""]
    lines += ["## Observed exchange", ""]
    for entry in t.get("entries", []):
        if entry.get("kind") == "comment":
            lines += ["", f"_{entry['text']}_", ""]
            continue
        req, resp = entry.get("request", {}), entry.get("response", {})
        role = entry.get("role", "subject")
        prefix = "" if role == "subject" else f"({role}) "
        line = f"{prefix}{req.get('method', '?')} {req.get('url', req.get('path', ''))}"
        block = ["```http", line]
        if req.get("body") is not None:
            block += ["", json.dumps(req["body"], indent=2)]
        block += ["", f"→ {resp.get('status', '?')}"]
        location = (resp.get("headers") or {}).get("location")
        if location:
            block.append(f"  Location: {location}")
        if resp.get("body") is not None:
            body = json.dumps(resp["body"], indent=2)
            if len(body) > 1200:
                body = body[:1200] + "\n… truncated"
            block.append(body)
        block.append("```")
        lines += block
    return lines


